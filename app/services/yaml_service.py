def _yaml_item_to_internal(item: dict) -> dict:
    """
    Convert a single YAML flow item to the internal format used by the app.

    YAML chain format:
        {"chain": {"prefix": "name", "transitions": [...], "fps": 16, ...}}

    Internal chain format (matches what batch_transitions.py expects):
        {"chain": [...steps...], "chain_prefix": "name", "fps": 16, ...}

    YAML talk format:
        {"type": "talk", "audio": "voice.mp3", "width": 480, "height": 832, ...}

    Internal talk format: same dict, passed through verbatim.
    """
    if item.get("break"):
        result = {"break": True}
        if item.get("label"):
            result["label"] = item["label"]
        return result
    if item.get("type") == "scene_break":
        return {"type": "scene_break", "name": item.get("name", "")}
    if "header" in item:
        return {"header": item["header"]}
    if item.get("type") == "multichain":
        # Pass through verbatim — same as talk/multitalk/dubit, no dict/list reshaping
        return dict(item)
    if "chain" in item:
        chain_data = item["chain"]
        if not isinstance(chain_data, dict):
            return item
        transitions = chain_data.get("transitions", [])
        result: dict[str, Any] = {
            "chain":        transitions,
            "chain_prefix": chain_data.get("prefix", "chain"),
        }
        for k in ("backend", "duration", "fps", "steps", "cfg", "neg", "blocks_to_swap", "width", "height", "frame_interpolation", "use_lightning", "atlascloud_resolution", "atlascloud_prompt_extend"):
            if k in chain_data and chain_data[k] is not None:
                result[k] = chain_data[k]
        return result
    if item.get("type") == "talk":
        # Pass through verbatim — all fields (audio, width, height, pos) preserved
        return dict(item)
    # Regular file item — copy verbatim
    return dict(item)


def _internal_item_to_yaml(item: dict) -> dict:
    """
    Convert a single internal flow item back to YAML format.
    Inverse of _yaml_item_to_internal().
    """
    if item.get("break"):
        result = {"break": True}
        if item.get("label"):
            result["label"] = item["label"]
        return result
    if item.get("type") == "scene_break":
        return {"type": "scene_break", "name": item.get("name", "")}
    if "header" in item:
        return {"header": item["header"]}
    if item.get("type") == "multichain":
        # Pass through verbatim — same as talk/multitalk/dubit, no dict/list reshaping
        return dict(item)
    if "chain" in item:
        chain_prefix = item.get("chain_prefix", "chain")
        chain_data: dict[str, Any] = {
            "prefix":      chain_prefix,
            "transitions": item.get("chain", []),
        }
        for k in ("backend", "duration", "fps", "steps", "cfg", "neg", "blocks_to_swap", "width", "height", "frame_interpolation", "use_lightning", "atlascloud_resolution", "atlascloud_prompt_extend"):
            if k in item and item[k] is not None:
                chain_data[k] = item[k]
        return {"chain": chain_data}
    if item.get("type") == "talk":
        # Pass through verbatim
        return dict(item)
    return dict(item)


def yaml_flow_to_internal(yaml_flow: list) -> list[dict]:
    """Convert a YAML 'flow' list to internal format."""
    return [_yaml_item_to_internal(item) for item in yaml_flow if isinstance(item, dict)]


def internal_flow_to_yaml(internal_flow: list) -> list:
    """Convert internal flow list to YAML-format list."""
    return [_internal_item_to_yaml(item) for item in internal_flow if isinstance(item, dict)]


