# Python code generator: YAML → .py
# ============================================================

def _py_val(val: Any, indent: int = 0) -> str:
    """Recursively format a Python value as valid Python source code."""
    pad = " " * indent

    if val is None:
        return "None"
    if isinstance(val, bool):
        return "True" if val else "False"
    if isinstance(val, (int, float)):
        return repr(val)
    if isinstance(val, str):
        if "\n" in val:
            # Use triple-quoted string; escape any existing triple-quotes
            escaped = val.replace('"""', r'\"\"\"')
            # Strip trailing whitespace on each line to keep .py clean
            lines = [line.rstrip() for line in escaped.split("\n")]
            body = "\n".join(lines)
            return f'"""{body}"""'
        return repr(val)
    if isinstance(val, (list, tuple)):
        if not val:
            return "[]" if isinstance(val, list) else "()"
        inner_indent = indent + 4
        items = [" " * inner_indent + _py_val(v, inner_indent) for v in val]
        inner = ",\n".join(items)
        o, c = ("[", "]") if isinstance(val, list) else ("(", ")")
        return f"{o}\n{inner},\n{pad}{c}"
    if isinstance(val, dict):
        if not val:
            return "{}"
        inner_indent = indent + 4
        items = [
            " " * inner_indent + repr(k) + ": " + _py_val(v, inner_indent)
            for k, v in val.items()
        ]
        inner = ",\n".join(items)
        return f"{{\n{inner},\n{pad}}}"
    return repr(val)


def _flow_list_to_py(flow: list, var_name: str) -> str:
    """Render a flow list as a Python assignment: VAR_NAME = [...]."""
    if not flow:
        return f"{var_name} = []\n"

    lines = [f"{var_name} = ["]
    for item in flow:
        if not isinstance(item, dict):
            continue
        if item.get("break"):
            lines.append('    {"break": True},')
            lines.append("")
            continue
        if "header" in item:
            header_text = str(item["header"])
            bar = "─" * max(4, 54 - len(header_text) - 2)
            lines.append(f"")
            lines.append(f"    # ── {header_text} {bar}")
            continue
        if item.get("type") == "multichain":
            # multichain item — render as plain dict, verbatim (same as talk/multitalk)
            lines.append("    {")
            for k, v in item.items():
                vr = _py_val(v, 8)
                lines.append(f'        {repr(k)}: {vr},')
            lines.append("    },")
            lines.append("")
            continue
        if "chain" in item:
            # chain item — keep internal format (what batch_transitions expects)
            chain_steps = item.get("chain", [])
            chain_prefix = item.get("chain_prefix", "chain")
            lines.append("    {")
            lines.append('        "chain": [')
            for step in chain_steps:
                lines.append("            {")
                for k, v in step.items():
                    vr = _py_val(v, 16)
                    lines.append(f'                {repr(k)}: {vr},')
                lines.append("            },")
            lines.append("        ],")
            lines.append(f'        "chain_prefix": {repr(chain_prefix)},')
            for k in ("backend", "duration", "fps", "steps", "cfg", "neg", "blocks_to_swap", "width", "height", "frame_interpolation", "use_lightning", "atlascloud_resolution", "atlascloud_prompt_extend"):
                if k in item:
                    vr = _py_val(item[k], 8)
                    lines.append(f'        {repr(k)}: {vr},')
            lines.append("    },")
            lines.append("")
            continue
        if item.get("type") in ("talk", "multitalk"):
            # talk/multitalk items — render as plain dict
            lines.append("    {")
            for k, v in item.items():
                vr = _py_val(v, 8)
                lines.append(f'        {repr(k)}: {vr},')
            lines.append("    },")
            lines.append("")
            continue
        # Regular file item
        lines.append("    {")
        for k, v in item.items():
            vr = _py_val(v, 8)
            lines.append(f'        {repr(k)}: {vr},')
        lines.append("    },")
    lines.append("]")
    return "\n".join(lines) + "\n"


