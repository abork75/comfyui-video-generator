def _check_flow_item(item: Any, idx: int) -> list[str]:
    errors: list[str] = []
    if not isinstance(item, dict):
        return [f"flow[{idx}]: must be a mapping, got {type(item).__name__}"]
    if item.get("break"):
        return []
    if "header" in item:
        return []  # header items are display-only, always valid
    if item.get("type") == "scene_break":
        return []  # scene_break items are always valid
    if item.get("type") == "multichain":
        chain = item.get("chain")
        if not isinstance(chain, list) or len(chain) == 0:
            errors.append(f"flow[{idx}].multichain: 'chain' must be a non-empty list")
        return errors
    if "chain" in item:
        chain = item["chain"]
        if not isinstance(chain, dict):
            errors.append(f"flow[{idx}].chain: must be a mapping")
            return errors
        t = chain.get("transitions")
        if t is None:
            errors.append(f"flow[{idx}].chain: missing 'transitions' list")
        elif not isinstance(t, list) or len(t) == 0:
            errors.append(f"flow[{idx}].chain: 'transitions' must be a non-empty list")
        return errors
    if item.get("type") == "talk":
        audio = item.get("audio")
        if audio is None:
            errors.append(f"flow[{idx}].talk: 'audio' is required")
        elif isinstance(audio, dict):
            # Single entry as dict: {file, pos, neg}
            if not audio.get("file"):
                errors.append(f"flow[{idx}].talk: audio dict must have 'file'")
        elif isinstance(audio, str):
            pass  # plain filename — OK
        elif isinstance(audio, list):
            if len(audio) == 0:
                errors.append(f"flow[{idx}].talk: 'audio' list must not be empty")
            else:
                for ei, entry in enumerate(audio):
                    if isinstance(entry, str):
                        pass  # plain filename — OK
                    elif isinstance(entry, dict):
                        if not entry.get("file"):
                            errors.append(
                                f"flow[{idx}].talk: audio[{ei}] dict must have 'file'"
                            )
                    else:
                        errors.append(
                            f"flow[{idx}].talk: audio[{ei}] must be a filename or dict"
                        )
        else:
            errors.append(f"flow[{idx}].talk: 'audio' must be a string, dict, or list")
        return errors
    if item.get("type") == "multitalk":
        return errors
    if item.get("type") == "dubit":
        return errors
    if "file" not in item:
        errors.append(f"flow[{idx}]: must have 'file', 'break', 'chain', or 'type: talk/multitalk/dubit'")
    return errors


def validate_yaml_doc(doc: Any) -> list[str]:
    """Validate a parsed YAML document. Returns list of error strings."""
    errors: list[str] = []
    if not isinstance(doc, dict):
        return ["Document must be a YAML mapping"]
    if not doc.get("project_folder"):
        errors.append("'project_folder' is required")
    flow = doc.get("flow")
    if flow is None:
        errors.append("'flow' list is required")
    elif not isinstance(flow, list):
        errors.append("'flow' must be a list")
    else:
        for i, item in enumerate(flow):
            errors.extend(_check_flow_item(item, i))
    flow_test = doc.get("flow_test")
    if flow_test is not None:
        if not isinstance(flow_test, list):
            errors.append("'flow_test' must be a list")
        else:
            for i, item in enumerate(flow_test):
                errors.extend(_check_flow_item(item, i))
    return errors


