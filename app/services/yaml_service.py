# Keys that are redundant / internal and should not appear in YAML
_SKIP_KEYS = {
    "FLOW", "FLOW_FULL", "FLOW_TEST",
    "USE_TEST_FLOW", "PROJECT_FOLDER",
    "FORCE_RESOLUTION", "DEFAULT_RESOLUTION",
    "DEFAULT_BACKEND", "DEFAULT_FPS", "DEFAULT_STEPS", "DEFAULT_CFG",
    "DEFAULT_DURATION", "DEFAULT_BLOCKS_TO_SWAP", "DEFAULT_SEED",
    "SKIP_MISSING", "SKIP_EXISTED", "IMAGE_QUALITY",
    "ASPECT_RATIO_TOLERANCE", "ASPECT_RATIO_STRATEGY",
    "MIN_WIDTH", "MIN_HEIGHT", "MAX_WIDTH", "MAX_HEIGHT",
    "DEFAULT_POSITIVE_PROMPT", "DEFAULT_NEGATIVE_PROMPT",
    "DEFAULT_AUDIO_PROMPT", "DEFAULT_AUDIO_NEGATIVE_PROMPT",
    "GENERIC_PROMPTS", "POSTPROCESSING", "DEBUG_LOG",
    # cloud backend — kept separately
    "COMFY_ICU_WORKFLOW_ID", "WORKFLOW_TEMPLATE_PATH",
    # linux backend paths — now stored in 'linux_backend:' YAML section (optional per-project override)
    "CONFIG_PATH", "WORKFLOWS_PATH", "COMFYUI_OUTPUT_FOLDER", "API_URL",
}


def _get_both_flows(py_path: Path) -> tuple[list | None, list | None]:
    """
    Return (FLOW_FULL, FLOW_TEST) from a .py file using AST extraction.
    Either can be None if not found.
    """
    content = py_path.read_text(encoding="utf-8", errors="replace")
    g = extract_globals(content)
    full = g.get("FLOW_FULL") if isinstance(g.get("FLOW_FULL"), list) else None
    test = g.get("FLOW_TEST") if isinstance(g.get("FLOW_TEST"), list) else None
    if full is None:
        # Fallback: try plain FLOW
        plain = g.get("FLOW")
        if isinstance(plain, list):
            full = plain
    return full, test


def _build_yaml_doc_from_globals(g: dict, full_flow: list | None, test_flow: list | None) -> dict:
    """Assemble the YAML document dict from extracted globals."""
    # Defaults section
    res = g.get("FORCE_RESOLUTION") or g.get("DEFAULT_RESOLUTION")
    defs: dict[str, Any] = {}
    if res:
        defs["resolution"] = list(res)
    for yaml_key, py_key, default in [
        ("backend",        "DEFAULT_BACKEND",        None),
        ("fps",            "DEFAULT_FPS",            None),
        ("steps",          "DEFAULT_STEPS",          None),
        ("cfg",            "DEFAULT_CFG",            None),
        ("duration",       "DEFAULT_DURATION",       None),
        ("blocks_to_swap",      "DEFAULT_BLOCKS_TO_SWAP",      None),
        ("frame_interpolation", "DEFAULT_FRAME_INTERPOLATION", None),
    ]:
        v = g.get(py_key)
        if v is not None:
            defs[yaml_key] = v

    doc: dict[str, Any] = {
        "project_folder": g.get("PROJECT_FOLDER", ""),
    }
    if defs:
        doc["defaults"] = defs

    use_test = bool(g.get("USE_TEST_FLOW", False))
    doc["use_test_flow"] = use_test

    # Linux / local backend paths
    lb: dict[str, Any] = {}
    for yaml_key, py_key in [
        ("config_path",           "CONFIG_PATH"),
        ("workflows_path",        "WORKFLOWS_PATH"),
        ("comfyui_output_folder", "COMFYUI_OUTPUT_FOLDER"),
        ("api_url",               "API_URL"),
    ]:
        v = g.get(py_key)
        if v is not None:
            lb[yaml_key] = v
    if lb:
        doc["linux_backend"] = lb

    if full_flow is not None:
        doc["flow"] = internal_flow_to_yaml(full_flow)
    if test_flow is not None:
        doc["flow_test"] = internal_flow_to_yaml(test_flow)

    return doc


class _LiteralStr(str):
    """Marker for strings that should be dumped as YAML literal blocks (|)."""


def _literal_representer(dumper: yaml.Dumper, data: _LiteralStr) -> yaml.ScalarNode:
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")


# These keys always use | block style — even single-line — so they're easy to edit.
_FORCE_LITERAL_KEYS = {"pos", "neg"}


def _make_literal(val: Any, _key: str | None = None) -> Any:
    """
    Recursively wrap strings in _LiteralStr so PyYAML emits them with | style.
    - Multiline strings: always literal.
    - pos / neg fields: always literal (even one-liners) for easy hand-editing.
    """
    if isinstance(val, str):
        if "\n" in val or _key in _FORCE_LITERAL_KEYS:
            return _LiteralStr(val)
        return val
    if isinstance(val, list):
        return [_make_literal(v) for v in val]
    if isinstance(val, dict):
        return {k: _make_literal(v, _key=k) for k, v in val.items()}
    return val


# ── YAML pretty-printer ──────────────────────────────────────────────────────

_SECTION_LABEL: dict[str, str] = {
    "flow":      "FLOW — lista generacji",
    "flow_test": "FLOW_TEST — lista testowa",
}


def _beautify_yaml(text: str) -> str:
    """
    Post-process raw PyYAML output for human readability:

    1. Blank line before every top-level key   (separates: defaults / flow / …)
    2. Section comment block before flow: and flow_test:
    3. Blank line before every top-level list item  (separates flow entries)
    """
    lines = text.split("\n")
    result: list[str] = []

    for line in lines:
        # ── Classify this line ───────────────────────────────────────────
        is_top_key = (
            bool(line)
            and not line[0].isspace()
            and not line.startswith("#")
            and not line.startswith("-")
            and ":" in line
        )
        is_top_item = line.startswith("- ") or line == "-"

        # ── 1. Blank line before every top-level key ─────────────────────
        if is_top_key and result and result[-1] != "":
            result.append("")

        # ── 2. Section comment for flow / flow_test ───────────────────────
        if is_top_key:
            key_name = line.split(":")[0].strip()
            if key_name in _SECTION_LABEL:
                bar = "# " + "─" * 58
                result.append(bar)
                result.append(f"# {_SECTION_LABEL[key_name]}")
                result.append(bar)

        # ── 3. Blank line before top-level list items ────────────────────
        if is_top_item:
            # Find the last non-blank line already written
            prev_non_blank = next((r for r in reversed(result) if r != ""), "")
            # Don't add blank right after the section header key (e.g. "flow:")
            if prev_non_blank and not prev_non_blank.rstrip().endswith(":"):
                if result and result[-1] != "":
                    result.append("")

        result.append(line)

    return "\n".join(result)


def _yaml_dump(doc: dict) -> str:
    """Dump a dict to YAML text with literal block style and human-friendly spacing."""
    dumper = yaml.Dumper
    dumper.add_representer(_LiteralStr, _literal_representer)
    raw = yaml.dump(
        _make_literal(doc),
        Dumper=dumper,
        default_flow_style=False,
        allow_unicode=True,
        sort_keys=False,
        width=10_000,      # never wrap — long strings stay on one line until | kicks in
    )
    return _beautify_yaml(raw)


def migrate_py_to_yaml(py_path: Path, out_path: Path | None = None) -> Path:
    """
    Migrate a RUN_*.py file to a RUN_*.yaml file.

    Parameters
    ----------
    py_path : Path
        Path to the source .py file.
    out_path : Path | None
        Destination .yaml path.  Defaults to same dir/stem but .yaml.

    Returns
    -------
    Path
        Path to the written .yaml file.

    Raises
    ------
    FileNotFoundError
        If py_path does not exist.
    ValueError
        If no FLOW could be extracted from the .py file.
    """
    if not py_path.exists():
        raise FileNotFoundError(f"Python RUN file not found: {py_path}")

    if out_path is None:
        out_path = py_path.with_suffix(".yaml")

    content = py_path.read_text(encoding="utf-8", errors="replace")
    g = extract_globals(content)
    full_flow, test_flow = _get_both_flows(py_path)

    if full_flow is None and test_flow is None:
        raise ValueError(f"Could not extract any FLOW from {py_path.name}")

    doc = _build_yaml_doc_from_globals(g, full_flow, test_flow)

    # Validate before writing
    errors = validate_yaml_doc(doc)
    if errors:
        # Non-fatal: warn but still write (project_folder might be empty etc.)
        header = (
            f"# WARNING: validation issues found during migration:\n"
            + "".join(f"#   - {e}\n" for e in errors)
            + "#\n"
        )
    else:
        header = (
            f"# Migrated from: {py_path.name}\n"
            f"# Migration date: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
            f"# Edit this file freely — regenerate .py with generate_py_from_yaml()\n#\n"
        )

    yaml_text = header + _yaml_dump(doc)
    out_path.write_text(yaml_text, encoding="utf-8")
    return out_path


def get_yaml_globals(yaml_path: Path) -> dict | None:
    """
    Return the non-flow sections of a YAML RUN file for the settings editor.
    Returns None if the file does not exist or cannot be parsed.
    """
    if not yaml_path.exists():
        return None
    try:
        doc = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    except Exception:
        return None
    if not isinstance(doc, dict):
        return None
    return {
        "project_folder":  doc.get("project_folder", ""),
        "use_test_flow":   bool(doc.get("use_test_flow", False)),
        "defaults":        dict(doc.get("defaults") or {}),
        "linux_backend":   dict(doc.get("linux_backend") or {}),
    }


def save_yaml_globals(yaml_path: Path, globals_data: dict) -> None:
    """
    Update non-flow sections (project_folder, defaults, linux_backend, use_test_flow)
    of a YAML RUN file without touching the flow lists.
    """
    if not yaml_path.exists():
        raise FileNotFoundError(f"YAML file not found: {yaml_path}")

    doc = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict):
        raise ValueError("YAML document is not a mapping")

    allowed = {"project_folder", "defaults", "linux_backend", "use_test_flow"}
    for key in allowed:
        if key in globals_data:
            val = globals_data[key]
            # Remove section entirely when an empty dict/string is passed
            if val == "" or val == {} or val is None:
                doc.pop(key, None)
            else:
                doc[key] = val

    errors = validate_yaml_doc(doc)
    if errors:
        raise ValueError("YAML validation errors:\n" + "\n".join(f"  • {e}" for e in errors))

    header = (
        f"# {yaml_path.name}\n"
        f"# Edited: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        f"# Edit this file freely — regenerate .py with generate_py_from_yaml()\n#\n"
    )
    yaml_path.write_text(header + _yaml_dump(doc), encoding="utf-8")


def create_run_from_globals(
    new_name: str,
    out_dir: Path,
    source_yaml: Path | None = None,
) -> Path:
    """
    Create a new RUN_*.yaml by cloning the global settings from *source_yaml*
    (project_folder, defaults, linux_backend) and leaving flow empty.

    If *source_yaml* is None or unreadable, sensible empty defaults are used.

    Parameters
    ----------
    new_name:
        Project name.  If it doesn't start with ``RUN_`` that prefix is added
        automatically.  ``.yaml`` extension is appended if missing.
    out_dir:
        Directory where the new file is created (normally RUNS_FOLDER).
    source_yaml:
        Optional path to the YAML file to copy globals from.

    Returns
    -------
    Path
        Path to the newly created .yaml file.

    Raises
    ------
    FileExistsError
        If a file with the computed name already exists.
    """
    # Normalise filename
    stem = new_name.strip()
    if not stem.upper().startswith("RUN_"):
        stem = f"RUN_{stem}"
    if not stem.endswith(".yaml"):
        stem = f"{stem}.yaml"

    out_path = out_dir / stem
    if out_path.exists():
        raise FileExistsError(f"Plik już istnieje: {stem}")

    # Read globals from source
    globals_data: dict = {}
    if source_yaml is not None and source_yaml.exists():
        try:
            raw = get_yaml_globals(source_yaml)
            if isinstance(raw, dict):
                globals_data = raw
        except Exception:
            pass

    # New projects only store project_folder + flow.
    # defaults and linux_backend come from app_config.yaml (global),
    # so we don't copy them — keeps new YAMLs minimal.
    doc: dict = {"project_folder": "", "use_test_flow": False, "flow": []}

    header = (
        f"# {stem}\n"
        f"# Created: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        f"# Edit this file freely — regenerate .py with generate_py_from_yaml()\n#\n"
    )
    out_path.write_text(header + _yaml_dump(doc), encoding="utf-8")
    return out_path


def save_yaml_flow(yaml_path: Path, new_flow: list, flow_key: str = "flow") -> None:
    """
    Overwrite the 'flow' (or 'flow_test') list in a YAML RUN file.

    Parameters
    ----------
    yaml_path : Path
        The .yaml file to update.
    new_flow : list
        New flow items in *internal* format (chain items have chain_prefix + chain keys).
    flow_key : str
        Which key to update: 'flow' or 'flow_test'.
    """
    if not yaml_path.exists():
        raise FileNotFoundError(f"YAML file not found: {yaml_path}")

    doc = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    if not isinstance(doc, dict):
        raise ValueError("YAML document is not a mapping")

    doc[flow_key] = internal_flow_to_yaml(new_flow)

    errors = validate_yaml_doc(doc)
    if errors:
        raise ValueError("YAML validation errors:\n" + "\n".join(f"  • {e}" for e in errors))

    header = (
        f"# {yaml_path.name}\n"
        f"# Edited: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        f"# Edit this file freely — regenerate .py with generate_py_from_yaml()\n#\n"
    )
    yaml_path.write_text(header + _yaml_dump(doc), encoding="utf-8")


def reformat_yaml(yaml_path: Path) -> Path:
    """
    Re-parse an existing RUN_*.yaml and re-write it with the current pretty formatter.

    Useful after updating the formatter (new blank lines, | style, section headers)
    to apply the new style without losing any data.

    Returns the same path (file is overwritten in place).
    Raises FileNotFoundError / ValueError on problems.
    """
    if not yaml_path.exists():
        raise FileNotFoundError(f"YAML file not found: {yaml_path}")

    doc = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    errors = validate_yaml_doc(doc)
    if errors:
        raise ValueError("YAML validation errors:\n" + "\n".join(f"  • {e}" for e in errors))

    header = (
        f"# {yaml_path.name}\n"
        f"# Reformatted: {datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        f"# Edit this file freely — regenerate .py with generate_py_from_yaml()\n#\n"
    )
    yaml_path.write_text(header + _yaml_dump(doc), encoding="utf-8")
    return yaml_path
