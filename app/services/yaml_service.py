def get_yaml_flow(yaml_path: Path) -> dict | None:
    """
    Extract flow data from a YAML RUN file.
    Returns the same dict shape as run_file_service.get_run_flow().
    """
    if not yaml_path.exists():
        return None

    try:
        doc = yaml.safe_load(yaml_path.read_text(encoding="utf-8"))
    except Exception:
        return None

    if not isinstance(doc, dict):
        return None

    use_test = bool(doc.get("use_test_flow", False))
    has_full = isinstance(doc.get("flow"), list)
    has_test = isinstance(doc.get("flow_test"), list)

    if use_test and has_test:
        raw, flow_type = doc["flow_test"], "test"
    elif has_full:
        raw, flow_type = doc["flow"], "full"
    elif has_test:
        raw, flow_type = doc["flow_test"], "test"
    else:
        return None

    flow = yaml_flow_to_internal(raw)

    return {
        "flow":          flow,
        "flow_type":     flow_type,
        "use_test":      use_test,
        "has_test_flow": has_test,
        "has_full_flow": has_full,
        "item_count":    len(flow),
    }


