def load_yaml_run(yaml_path: Path) -> dict | None:
    """
    Load and parse a YAML RUN file.
    Returns the same info-dict shape as run_file_service._build_run_info().
    Returns None if the file does not exist.
    Errors are stored in the 'error' key.
    """
    if not yaml_path.exists():
        return None

    # Use a pseudo-.py name for display_name so the helper works
    display_stem = yaml_path.stem  # e.g. "RUN_011_praca_w_postapo"
    info: dict[str, Any] = {
        "filename":              yaml_path.name,
        "display_name":          make_display_name(display_stem + ".py"),
        "compatibility":         "yaml",
        "project_folder":        None,
        "force_resolution":      None,
        "default_resolution":    None,
        "default_backend":       None,
        "default_blocks_to_swap":      None,
        "default_fps":                 None,
        "default_steps":               None,
        "default_frame_interpolation": None,
        "error":                       None,
        "source":                "yaml",
    }

    try:
        content = yaml_path.read_text(encoding="utf-8")
    except OSError as e:
        info["error"] = str(e)
        return info

    try:
        doc = yaml.safe_load(content)
    except yaml.YAMLError as e:
        mark = getattr(e, 'problem_mark', None)
        info["error"] = f"YAML parse error: {e}"
        info["syntax_error"] = {
            "msg":    getattr(e, 'problem', str(e)),
            "line":   (mark.line + 1) if mark else None,
            "offset": (mark.column + 1) if mark else None,
            "text":   (mark.get_snippet() if (mark and hasattr(mark, 'get_snippet')) else None),
        }
        return info

    errors = validate_yaml_doc(doc)
    if errors:
        info["error"] = "; ".join(errors)
        return info

    defs = doc.get("defaults") or {}
    res = defs.get("resolution")
    info["project_folder"]         = doc.get("project_folder")
    info["force_resolution"]       = tuple(res) if res else None
    info["default_resolution"]     = tuple(res) if res else None
    info["default_backend"]              = defs.get("backend", "linux")
    info["default_blocks_to_swap"]      = defs.get("blocks_to_swap")
    info["default_fps"]                 = defs.get("fps")
    info["default_steps"]               = defs.get("steps")
    info["default_frame_interpolation"] = defs.get("frame_interpolation")

    return info


