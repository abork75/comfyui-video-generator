"""
YAML service — read/write/migrate RUN files in YAML format.

Design (Option B): YAML is the human-editable source of truth.
    RUN_*.yaml  ← edited by user (and soon by the GUI)
    RUN_*.py    ← auto-generated by generate_py_from_yaml(); never manually edited

Main public API
───────────────
    load_yaml_run(path)          → info dict  (same shape as _build_run_info)
    get_yaml_flow(path)          → flow dict  (same shape as get_run_flow)
    generate_py_from_yaml(path)  → write RUN_*.py next to the .yaml
    migrate_py_to_yaml(path)     → write RUN_*.yaml next to the .py (migration)
    validate_yaml_doc(doc)       → list[str] of errors (empty = ok)

YAML schema (canonical)
───────────────────────
    project_folder: "C:/path/to/film"

    defaults:
      backend: linux
      fps: 16
      steps: 6
      cfg: 2.0
      blocks_to_swap: 35
      resolution: [1024, 1024]   # becomes FORCE_RESOLUTION; null = auto
      duration: 2
      skip_existed: true

    use_test_flow: false

    flow:                        # = FLOW_FULL
      - file: "frame.png"
        duration: 5
        pos: |
          Smooth cinematic zoom...
        neg: "blurry, low quality"

      - break: true

      - chain:
          prefix: my_chain
          fps: 16
          steps: 6
          cfg: 2.0
          neg: "static, frozen"
          transitions:           # ← chosen name for chain step list
            - duration: 3
              pos: |
                Step 1 prompt...
            - duration: 3
              pos: |
                Step 2 prompt...

    flow_test:                   # = FLOW_TEST (optional)
      - file: "test.png"
        duration: 2
        pos: "NONE"
        neg: "blurry"
"""

